#ifndef __UI_H
#define __UI_H

#include "lvgl.h"

/* ============================================================================
 *  小狗表情界面
 * ----------------------------------------------------------------------------
 *  屏幕 = 两只眼睛 + 一张嘴。
 *
 *  核心思路：把一个表情描述成【一组数字】，而不是一张画好的图片。
 *    眼睛 = 圆角矩形。圆角拉到最大时，宽=高就是正圆，宽>高就是胶囊
 *           （胶囊就是「眯眼」的关键形状）。
 *    嘴巴 = 一条直线，或者一段弧。
 *
 *  这样一来「表情库」就变成了一张数字表格，加一个表情 = 加一行数字。
 *  以后想做动画也是水到渠成 —— 动画不过是「按时间在两组数字之间插值」。
 * ========================================================================== */

/* 一个表情 = 一组数字。尺寸单位都是像素。 */
typedef struct {
    int16_t eye_w;      /* 单只眼睛的宽度 */

    int16_t eye_h;      /* 单只眼睛的高度。
                         *   等于 eye_w -> 正圆
                         *   远小于 eye_w -> 扁成一条缝 = 眯眼 */

    int16_t eye_gap;    /* 两只眼睛【内侧边缘】之间的空隙。
                         * 注意不是中心距，是中间那道缝有多宽。 */

    int16_t eye_dy;     /* 眼睛整体上下微调。正数往下，负数往上。
                         * 惊讶时往上抬，难过/生气时往下压。 */

    int16_t mouth_w;    /* 嘴的宽度。
                         * ⚠ 弧形嘴的弯曲深度 = mouth_w / 2，
                         *   所以嘴越宽，弯得越厉害，这两者是联动的。 */

    int16_t mouth_dir;  /* 嘴的弯向：
                         *   +1 = 向下弯，笑 ⌣
                         *   -1 = 向上弯，撇嘴 ⌢
                         *    0 = 一条直线 ─      */
} ui_data_t;

/* 搭好界面骨架。开机时调用一次。
 * ⚠ 调用前必须已经持有 LVGL 锁（lvgl_port_lock）。 */
void ui_create(lv_display_t *disp);

/* 换一个表情。之后反复调用，只改数字，不会重建任何控件。
 * ⚠ 同样必须持有 LVGL 锁：
 *       if (lvgl_port_lock(0)) { ui_update(&face); lvgl_port_unlock(); } */
void ui_update(const ui_data_t *face);

#endif /* __UI_H */
