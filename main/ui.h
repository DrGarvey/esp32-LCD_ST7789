#ifndef __UI_H
#define __UI_H

#include "lvgl.h"

/* ============================================================================
 * 界面模块
 * ----------------------------------------------------------------------------
 * 把「长什么样」和「怎么启动」分开：
 *   main.c  负责启动流程（初始化、加锁、解锁）
 *   ui.c    只负责界面长什么样
 *
 * 界面变复杂时，只需要改 ui.c，main.c 基本不用动。
 * ========================================================================== */

/* 创建整个界面。
 *
 * ⚠ 调用前必须已经持有 LVGL 锁（lvgl_port_lock），
 *    因为它内部会大量修改控件树。
 *
 * 参数 disp：bsp_lvgl_init() 返回的显示句柄。 */
void ui_create(lv_display_t *disp);

/* ---------------------------------------------------------------------------
 * 界面数据
 * ---------------------------------------------------------------------------
 * 「屏幕要显示什么」全部通过这个结构体传进来，ui_update() 负责把它写到屏幕上。
 *
 * 这样分的好处：界面代码（ui.c）不认识你的传感器、你的网络数据，
 * 它只认识这个结构体。以后换数据源，ui.c 一行都不用改。
 *
 * 想加新内容时的步骤：
 *   1. 在这里加一个字段，比如 const char *temperature;
 *   2. 在 ui.c 的 ui_create() 里把这个字段对应的控件指针存到 s_xxx 变量；
 *   3. 在 ui_update() 里加一行，把 data->temperature 写进那个控件。
 *
 * ⚠ 文字必须是纯英文/数字符号！
 *   当前用的是 LVGL 内置字体，里面【没有中文字形】，
 *   写中文会显示成一堆小方块或者直接不显示。中文要另外做字库（后面再说）。
 * ------------------------------------------------------------------------- */
typedef struct {
    const char *title;          /* 顶部标题文字，不能为 NULL */
    const char *status;         /* 底部状态文字，不能为 NULL */

    /* 三个色块里的文字。写成 const char *box_names[3] 也行，
     * 加 const 是提醒「这里只读、不会改你的字符串」。 */
    const char *box_names[3];

    /* 三个色块的背景色。⚠ 是 24 位 RGB888（0xRRGGBB），不是 RGB565！
     * 红 = 0xFF0000，绿 = 0x00FF00，蓝 = 0x0000FF。 */
    uint32_t    box_colors[3];
} ui_data_t;

/* ---------------------------------------------------------------------------
 * 用 data 里的内容刷新界面
 * ---------------------------------------------------------------------------
 * ⚠ 和其它界面操作一样，调用前【必须持有 LVGL 锁】：
 *
 *      if (lvgl_port_lock(0)) {
 *          ui_update(&my_data);
 *          lvgl_port_unlock();
 *      }
 *
 * 结构体里的字段【每次都会被全部应用】，没有「跳过某一项」的写法，
 * 所以每次调用都要把三项都填好（不变的就填原来的值）。
 * ------------------------------------------------------------------------- */
void ui_update(const ui_data_t *data);

#endif /* __UI_H */
